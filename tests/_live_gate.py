"""실 WebView2 게이트의 공용 예산과 **콜드 부팅 정책** (#411 CI 왕복의 승계).

## 이 파일이 있는 이유 — 부팅 한 번이 주사위 한 번이다

실 창 게이트는 파일마다 자식 프로세스를 띄우고, 그 자식은 WebView2 를 **콜드 부팅**한다.
러너에서 그 부팅은 확률적으로 멎는다 — 저장소가 이미 아는 결함류이고, 패키징 쪽은
`packaging/build.ps1` 의 `webview_boot_flake`(환경 서명 분류 뒤 유한 재시도, #477)로 그것을
흡수한다. 실 게이트 자식에는 그 장치가 없으므로, 여기서는 **노출 자체를 줄이는 쪽**으로 푼다.

정책 둘이 이 파일에 산다.

### 1. 콜드 부팅을 늘리지 않는다

새 실런타임 단언은 **기존 게이트의 창에 얹는다.** 새 파일 + 새 자식 + 새 창을 기본값으로
삼으면 부팅 수가 단계마다 하나씩 늘고, 한 run 이 전부 초록일 확률은 단조 감소한다 — R2 에
셋, R3-01 에 넷, R3-02 에 다섯이었고 R4·R5 가 같은 습관을 이으면 계속 는다.

이 저장소는 반대 형태를 이미 증명했다: `test_web_selftest_gate` 는 창 **두 번**으로 단언
**80 개**를 뽑는다. 실런타임 사실을 더 재고 싶으면 그 형태를 따른다 — 되읽기 표현식에 필드를
더하거나, 이미 서 있는 창에 단계를 붙인다. 부득이 새 창이 필요하면
`tests/test_live_gate_shape.py` 의 폐포가 그 증가를 **시끄럽게** 묻는다(조용한 증가 금지).

### 2. 예산은 넉넉하다 — 「느림」과 「멎음」을 가르는 자리에 둔다

예산이 하는 일은 **매달림을 유한 시간에 빨강으로 만드는 것**이지, 느린 러너를 탈락시키는
것이 아니다. 느림으로 빨강이 나면 그 빨강은 정보가 0 이고(코드는 멀쩡하다) 재주행 비용만
남는다. 그래서 값은 실측의 자릿수 위에 둔다:

- 로컬(웜 런타임): 자식 하나가 부팅·검사·해체까지 **4 초** 안에 완주.
- CI 정상: live 잡 전체가 부팅 여섯 번에 **2~3 분** — 부팅 하나당 20~30 초.
- 콜드 최초 부팅(WebView2 런타임 기동 + AV 스캔)이 그 위에 얹힌다.

`LIVE_PROBE_BUDGET_S` 는 그 정상값의 **약 10 배**이고, `LIVE_CHILD_TIMEOUT_S` 는 폴링 예산에
부팅·정리 여유를 더한 값이다. 이 두 상수가 실 게이트 넷의 **단일 출처**다 — 파일마다 제
숫자를 들면 「가장 촘촘한 예산이 형제와 자릿수로 벌어지는」 결함류가 그대로 재발한다
(`test_web_selftest_gate::test_the_tightest_probe_budget_is_not_an_outlier` 가 JS 프로브 층에서
같은 것을 잡는다).

값을 **줄이는** 변경은 사유와 함께 이 파일을 고쳐야 하고, 그 변경 자체가 리뷰 대상이다.
"""

from __future__ import annotations

#: 창 안 폴링 예산 — 자식이 자기 판정을 기다리는 상한. 콜드 부팅·AV 스캔·저속 러너를 품는다.
LIVE_PROBE_BUDGET_S = 240.0

#: 자식 프로세스 상한 — 폴링 예산 + 부팅·해체 여유. 초과는 「느림」이 아니라 전면 매달림이다.
LIVE_CHILD_TIMEOUT_S = 420.0
